import assert from 'node:assert/strict';
import fs from 'node:fs';

const read=file=>JSON.parse(fs.readFileSync(new URL(file,import.meta.url),'utf8'));
const matrix=read('../generated/compatible-rules.json');
const codex=read('../content/chaos-space-marines-codex-datasheets.en.json');
const pack=read('../content/chaos-space-marines-faction-pack.en.json');
const points=read('../content/chaos-space-marines-points.en.json');
const rows=Object.values(matrix.units).flat();
const rules=kind=>new Set(rows.filter(row=>row.kind===kind&&row.scope!=='core').map(row=>row.ruleId));
const pointId=(detachment,title)=>points.enhancements.find(item=>item.detachment.toLowerCase()===detachment.toLowerCase()&&item.title.toLowerCase()===title.toLowerCase())?.id;

assert.equal(matrix.schema,'chaos-space-marines-compatible-rules/v1');
assert.equal(codex.datasheets.length,54);
assert.equal(codex.legends.length,53);
assert.equal(Object.keys(matrix.units).length,54);
assert.deepEqual(new Set(Object.keys(matrix.units)),new Set(codex.datasheets.map(unit=>unit.id)));
for(const title of ['Khorne Berzerkers','Noise Marines','Plague Marines','Rubric Marines'])assert.ok(!codex.datasheets.some(unit=>unit.title===title),`${title} leaked into current CSM inventory`);
assert.equal(pack.detachments.length,9);
assert.equal(pack.detachments.reduce((sum,item)=>sum+item.stratagems.length,0),45);
assert.equal(pack.detachments.reduce((sum,item)=>sum+item.enhancements.length,0),30);
assert.deepEqual(rules('stratagem'),new Set(pack.detachments.flatMap(item=>item.stratagems.map(rule=>rule.id))));
assert.deepEqual(rules('enhancement'),new Set(pack.detachments.flatMap(detachment=>detachment.enhancements.map(item=>pointId(detachment.title,item.title)))));
assert.equal(new Set(rows.filter(row=>row.scope==='core').map(row=>row.ruleId)).size,10);
assert.ok(matrix.units['unit-defiler'].some(row=>row.detachmentId==='cult-of-the-arkifane'&&row.ruleId==='balefire-boon'),'Cult of the Arkifane VEHICLE grant is absent');
assert.ok(matrix.units['unit-lord-discordant-on-helstalker'].some(row=>row.detachmentId==='cult-of-the-arkifane'&&row.ruleId==='balefire-boon'),'Cult of the Arkifane SOUL FORGE grant is absent');
const nightmare=pointId('NIGHTMARE HUNT','Warp-Fuelled Thrusters'),dread=pointId('DREAD TALONS','Warp-Fuelled Thrusters');
assert.ok(rows.some(row=>row.ruleId===nightmare),'Nightmare Hunt Warp-Fuelled Thrusters identity is absent');
assert.ok(!rows.some(row=>row.ruleId===dread),'source-limited Dread Talons Warp-Fuelled Thrusters leaked into Compatible Rules');
for(const row of rows.filter(item=>item.scope!=='core'))assert.ok(pack.detachments.some(detachment=>detachment.id===row.detachmentId),`source-limited Detachment row ${row.detachmentId}`);
console.log(`CSM Compatible Rules QA passed: ${Object.keys(matrix.units).length} units, ${rows.length} rows, 45 Stratagems, 30 Enhancements and 10 Core Stratagems.`);
