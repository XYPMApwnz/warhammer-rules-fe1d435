import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=file=>JSON.parse(fs.readFileSync(path.join(root,file),'utf8'));
const source=read('sources/codex-secondary-consensus.en.json'),pack=read('content/chaos-space-marines-faction-pack.en.json'),related=read('content/chaos-space-marines-related-rules.en.json'),points=read('content/chaos-space-marines-points.en.json'),codex=read('content/chaos-space-marines-codex-datasheets.en.json'),manifest=read('sources/source-manifest.json');
assert.equal(source.records.length,89,'89/89 Codex records evaluated');
assert.deepEqual(source.summary.byType,{'army-rule':1,'detachment-rule':8,stratagem:48,enhancement:32});
assert.equal(source.summary.byStatus['SECONDARY CONSENSUS'],38);
assert.equal(source.summary.byStatus['SOURCE MISSING'],50);
assert.equal(source.summary.byStatus['SECONDARY CONFLICT'],1);
assert.equal(source.policy.guessed,0);
assert.equal(source.records.filter(record=>record.imported).length,38);
assert.ok(source.records.every(record=>record.imported===(record.status==='SECONDARY CONSENSUS')));
assert.ok(source.records.filter(record=>record.imported).every(record=>record.bsdataIdentity&&record.wahapediaIdentity));
assert.equal(source.imports.armyRules.length,0);
assert.equal(source.imports.detachments.length,8);
assert.equal(source.imports.detachments.filter(detachment=>detachment.rule).length,6);
assert.equal(source.imports.detachments.reduce((count,detachment)=>count+detachment.stratagems.length,0),0);
assert.equal(source.imports.detachments.reduce((count,detachment)=>count+detachment.enhancements.length,0),32);
assert.ok(source.imports.detachments.flatMap(detachment=>detachment.enhancements).every(item=>item.text.trim()&&item.provenance.authority==='secondary'));
assert.equal(Object.keys(source.imports.enhancementContracts).length,32);
assert.equal(pack.detachments.length,17);
assert.equal(pack.detachments.reduce((count,detachment)=>count+detachment.stratagems.length,0),45);
assert.equal(pack.detachments.reduce((count,detachment)=>count+detachment.enhancements.length,0),62);
assert.equal(pack.detachments.flatMap(detachment=>detachment.enhancements).filter(item=>!item.text?.trim()).length,0);
assert.equal(Object.keys(related.stratagems).length,45);
assert.equal(Object.keys(related.enhancements).length,62);
assert.equal(points.enhancements.length,62);
assert.equal(codex.datasheets.length,54);
assert.equal(manifest.gates.publishAsComplete,false);
const duplicate=pack.detachments.flatMap(detachment=>detachment.enhancements.map(item=>({detachment:detachment.title,...item}))).filter(item=>item.title.toLowerCase()==='warp-fuelled thrusters');
assert.equal(duplicate.length,2);
assert.equal(new Set(duplicate.map(item=>item.id)).size,2,'duplicate title remains Detachment-qualified');
assert.equal(fs.readdirSync(path.join(root,'mobile')).filter(file=>file.endsWith('.html')).length,74);
console.log('Chaos Space Marines secondary consensus QA PASS: 89 evaluated, 38 imported, 51 unresolved, 0 guessed.');
